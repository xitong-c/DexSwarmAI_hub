let language = 'zh';
try { language = localStorage.getItem('dexswarm-language') === 'en' ? 'en' : 'zh'; } catch (_) {}
const reader = document.getElementById('reader');
let manualLanguage = 'zh';
let currentPage = 1;
let returnFocus = null;
const pageCount = 6;

function applyLanguage(next) {
  language = next === 'en' ? 'en' : 'zh';
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = copy[language][el.dataset.i18n]; });
  document.querySelectorAll('[data-alt]').forEach(el => { el.alt = copy[language][el.dataset.alt]; });
  document.querySelectorAll('[data-label]').forEach(el => { el.setAttribute('aria-label', copy[language][el.dataset.label]); });
  document.getElementById('language-label').textContent = language === 'zh' ? 'EN' : '中文';
  document.getElementById('language-switch').setAttribute('aria-label', language === 'zh' ? 'Switch website to English' : '切换网站为中文');
  document.querySelector('nav').setAttribute('aria-label', language === 'zh' ? '主导航' : 'Main navigation');
  document.querySelectorAll('.wordmark').forEach(el => el.setAttribute('aria-label', language === 'zh' ? 'DexSwarm AI 首页' : 'DexSwarm AI home'));
  document.querySelector('.system-strip').setAttribute('aria-label', language === 'zh' ? '三大系统层' : 'Three system layers');
  document.title = language === 'zh' ? 'DexSwarm AI — 产品资料中心' : 'DexSwarm AI — Product Resource Hub';
  try { localStorage.setItem('dexswarm-language', language); } catch (_) {}
  if (reader.open) { buildThumbnails(); renderPage(); }
}

function buildThumbnails() {
  const container = document.getElementById('thumbnails');
  container.replaceChildren();
  for (let page = 1; page <= pageCount; page++) {
    const button = document.createElement('button');
    button.className = 'thumbnail';
    button.dataset.page = page;
    button.setAttribute('aria-label', language === 'zh' ? `第 ${page} 页` : `Page ${page}`);
    const image = document.createElement('img');
    image.src = `assets/manual-${manualLanguage}-${page}.webp`;
    image.alt = '';
    image.width = 82;
    image.height = 115;
    const label = document.createElement('span');
    label.textContent = String(page).padStart(2,'0');
    button.append(image,label);
    button.addEventListener('click', () => { currentPage = page; renderPage(); });
    container.append(button);
  }
}

function renderPage() {
  const img = document.getElementById('reader-page');
  img.hidden = false;
  document.getElementById('reader-error').hidden = true;
  img.src = `assets/manual-${manualLanguage}-${currentPage}.webp`;
  img.alt = language === 'zh' ? `${manualLanguage === 'zh' ? '中文版' : '英文版'}产品手册，第 ${currentPage} 页` : `${manualLanguage === 'zh' ? 'Chinese' : 'English'} product manual, page ${currentPage}`;
  document.getElementById('reader-title').textContent = language === 'zh' ? `产品手册 · ${manualLanguage === 'zh' ? '中文版' : '英文版'}` : `Product Manual · ${manualLanguage === 'zh' ? 'Chinese' : 'English'}`;
  document.getElementById('page-status').textContent = `${currentPage} / ${pageCount}`;
  document.getElementById('page-prev').disabled = currentPage === 1;
  document.getElementById('page-next').disabled = currentPage === pageCount;
  document.getElementById('reader-language').value = manualLanguage;
  ['reader-pdf','reader-download'].forEach(id => { document.getElementById(id).href = `manuals/dexswarm-product-manual-${manualLanguage}.pdf`; });
  document.querySelectorAll('.thumbnail').forEach(el => {
    if (Number(el.dataset.page) === currentPage) el.setAttribute('aria-current','page');
    else el.removeAttribute('aria-current');
  });
  document.getElementById('reader-scroll').scrollTop = 0;
}

function openReader(lang,trigger) {
  manualLanguage = lang === 'en' ? 'en' : 'zh';
  currentPage = 1;
  returnFocus = trigger;
  buildThumbnails();
  renderPage();
  reader.showModal();
  document.body.classList.add('reader-open');
  document.getElementById('reader-close').focus();
}

document.querySelectorAll('[data-preview]').forEach(el => el.addEventListener('click', () => openReader(el.dataset.preview,el)));
document.getElementById('language-switch').addEventListener('click', () => applyLanguage(language === 'zh' ? 'en' : 'zh'));
document.getElementById('reader-close').addEventListener('click', () => reader.close());
reader.addEventListener('close', () => { document.body.classList.remove('reader-open'); returnFocus?.focus(); });
reader.addEventListener('click', event => {
  if (event.target === reader) {
    const rect = reader.getBoundingClientRect();
    if (event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom) reader.close();
  }
});
document.getElementById('page-prev').addEventListener('click', () => { if(currentPage > 1) { currentPage--; renderPage(); } });
document.getElementById('page-next').addEventListener('click', () => { if(currentPage < pageCount) { currentPage++; renderPage(); } });
reader.addEventListener('keydown', event => {
  if (event.target.tagName === 'SELECT') return;
  if(event.key === 'ArrowLeft' && currentPage > 1) { event.preventDefault(); currentPage--; renderPage(); }
  if(event.key === 'ArrowRight' && currentPage < pageCount) { event.preventDefault(); currentPage++; renderPage(); }
});
document.getElementById('reader-language').addEventListener('change', event => {
  manualLanguage = event.target.value === 'en' ? 'en' : 'zh';
  buildThumbnails(); renderPage();
});
document.getElementById('reader-page').addEventListener('error', () => {
  document.getElementById('reader-page').hidden = true;
  document.getElementById('reader-error').hidden = false;
});
document.getElementById('year').textContent = new Date().getFullYear();
applyLanguage(language);
